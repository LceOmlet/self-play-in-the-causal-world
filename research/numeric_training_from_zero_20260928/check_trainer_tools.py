"""CPU fixture: actual official Trainer dispatch/masking/reward + real NsJail.

The initial response is scripted through TRL's public rollout_func hook; the
one-token follow-up is generated by a tiny random CPU GPT-2, not Qwen weights.
This fixture never trains and is never used by the production entry point.
"""
import os
os.environ['CUDA_VISIBLE_DEVICES'] = ''
import copy
import importlib.util
import inspect
import json
from pathlib import Path
import re
import shutil
import time

import torch
from datasets import Dataset
from transformers import AutoTokenizer, GPT2Config, GPT2LMHeadModel
from trl import GRPOConfig, GRPOTrainer
from cpt_world import CPTWorldEnvironment, WorldGrammar
from cpt_world.trl_environment import _training_row

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT/'preflights'/time.strftime('%Y%m%dT%H%M%SZ', time.gmtime())
OUT.mkdir(parents=True, exist_ok=False)
shutil.copy2(__file__, OUT/'driver.py')

def load(name):
    spec = importlib.util.spec_from_file_location('cpt_numeric_'+name, ROOT/'source'/f'{name}.py')
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod

adapter, backend = load('tool_mode'), load('secure_backend')
factory = backend.NsjailSessionFactory(OUT/'sessions')
environment = adapter.make_numeric_environment(CPTWorldEnvironment, factory)
tokenizer = AutoTokenizer.from_pretrained(os.environ.get('CPT_MODEL_DIR', '/models/Qwen/Qwen3.5-9B'), local_files_only=True)
row, _, _ = _training_row(WorldGrammar(), 7, 'ate')
terminal_template = row['prompt'][-1]['content'].split('To finish,')[-1]
states = re.findall(r'"(state_\d+)":', terminal_template)
assert states
terminal = {'type':'answer', 'effect':dict.fromkeys(states, 0.0)}
baseline = CPTWorldEnvironment()
baseline.reset(**row)
baseline_feedback = baseline.act(terminal)
baseline_reward = baseline.get_reward()

def scripted(prompts, trainer):
    prompt_ids, _, _ = trainer._tokenize_prompts(prompts)
    completions = []
    for i, (prompt, ids) in enumerate(zip(prompts, prompt_ids)):
        code1 = f'import numpy as np\nimport scipy as sp\nassert "answer_id" not in globals()\nanswer_id = {i}\nx = sp.linalg.solve([[2.,0.],[0.,4.]],[4.,8.])\nprint("NUMERIC_ONE_{i}", x.tolist())'
        code2 = f'import numpy as np\nassert answer_id == {i}\nassert np.allclose(x, [2.,2.])\nprint("NUMERIC_TWO_{i}", float(x.sum()))'
        calls = [
            {'type':'function','function':{'name':'numerics','arguments':{'code':code1}}},
            {'type':'function','function':{'name':'numerics','arguments':{'code':code2}}},
            {'type':'function','function':{'name':'shell','arguments':{'command':'must never run'}}},
            {'type':'function','function':{'name':'get_reward','arguments':{}}},
            {'type':'function','function':{'name':'act','arguments':{'command':terminal}}},
        ]
        full_text = tokenizer.apply_chat_template(prompt+[{'role':'assistant','content':'','tool_calls':calls}],
            tools=trainer.tools, chat_template=trainer.chat_template, enable_thinking=False, tokenize=False)
        prefix_text = tokenizer.decode(ids)
        assert full_text.startswith(prefix_text)
        # A rollout returns newly generated tokens; it must not re-tokenize the
        # full prompt (BPE at the suffix boundary can change prior token IDs).
        completions.append(tokenizer.encode(full_text[len(prefix_text):], add_special_tokens=False))
    return {'prompt_ids':prompt_ids,'completion_ids':completions,'logprobs':None}

config = GPT2Config(vocab_size=len(tokenizer), n_embd=8, n_layer=1, n_head=1,
                   n_positions=32768, eos_token_id=tokenizer.eos_token_id,
                   pad_token_id=tokenizer.pad_token_id, bos_token_id=tokenizer.eos_token_id)
model = GPT2LMHeadModel(config)
args = GRPOConfig(output_dir=str(OUT/'trainer'), use_cpu=True, bf16=False, fp16=False,
    max_steps=1, per_device_train_batch_size=1, gradient_accumulation_steps=4,
    generation_batch_size=4, num_generations=4, max_completion_length=2048,
    max_tool_calling_iterations=1, generation_kwargs={'max_new_tokens':1},
    use_vllm=False, use_liger_kernel=False, beta=0.0, scale_rewards='none',
    loss_type='dapo', remove_unused_columns=False, shuffle_dataset=False,
    gradient_checkpointing=False, report_to='none', save_strategy='no', disable_tqdm=True,
    chat_template_kwargs={'enable_thinking':False})
started = time.monotonic()
try:
    trainer = GRPOTrainer(model=model, args=args, train_dataset=Dataset.from_list([row]*4),
                         reward_funcs=[], processing_class=tokenizer,
                         environment_factory=environment, rollout_func=scripted)
    assert type(trainer) is GRPOTrainer
    assert {f.__name__ for f in trainer.tools} == {'act','numerics'}
    assert trainer.reward_func_names == ['CPTWorldNumericEnvironment']
    assert trainer.reward_weights.tolist() == [1.0]
    batch = trainer._generate_and_score_completions([copy.deepcopy(row) for _ in range(4)])
    assert int(batch['num_items_in_batch']) == int((batch['tool_mask']*batch['completion_mask']).sum())
    assert batch['tool_mask'].eq(0).sum() > 0
    assert all(env.episode.completed for env in trainer.environments)
    assert all(env._numeric_session is None for env in trainer.environments)
    assert [env.get_reward() for env in trainer.environments] == [baseline_reward]*4
    for i, (ids, mask) in enumerate(zip(batch['completion_ids'].tolist(),batch['tool_mask'].tolist())):
        for marker in [f'NUMERIC_ONE_{i}', f'NUMERIC_TWO_{i}']:
            # Both a code string and its returned output may contain the marker.
            # Require a returned occurrence masked out of policy loss.
            target = tokenizer.encode(marker, add_special_tokens=False)
            locations = [j for j in range(len(ids)-len(target)+1) if ids[j:j+len(target)] == target]
            assert any(all(v == 0 for v in mask[j:j+len(target)]) for j in locations), marker
    reward_log = {k:list(v) for k,v in trainer._logs['rewards'].items()}
    # Official reward assembly explicitly stores float32. Compare that same
    # representation, not Python float64 against a rounded logging tensor.
    (OUT/'reward-assembly.json').write_text(json.dumps({'owner_reward':baseline_reward,
                                                       'logged_rewards':reward_log},indent=2))
    assert reward_log['CPTWorldNumericEnvironment'] == [float(torch.tensor(baseline_reward,dtype=torch.float32))]*4
    metrics = {k:list(v) for k,v in trainer._metrics['train'].items()}
    assert metrics['tools/call_frequency'][-1] == 5
    assert metrics['tools/failure_frequency'][-1] == float(torch.tensor(0.4))
    result = {'passed':True,'gpu_used':False,'model':'tiny random GPT-2 CPU fixture',
        'qwen_weights_loaded':False,'production_training_updates':0,
        'tool_methods':['act','numerics'], 'sandbox_sessions':len(list((OUT/'sessions').glob('answer-*'))),
        'state_persistence_and_four_answer_isolation':True, 'unknown_tools_rejected':True,
        'numerical_output_loss_mask_zero':True, 'original_reward_preserved':True,
        'baseline_reward':baseline_reward,'reward_log':reward_log,'metrics':metrics,
        'seconds':time.monotonic()-started,'trainer_source':inspect.getfile(GRPOTrainer),
        'scope':'Actual Trainer public hook dispatch/mask/reward with scripted initial calls; not autonomous Qwen behavior or RL improvement.'}
    (OUT/'result.json').write_text(json.dumps(result,indent=2))
    (ROOT/'preflight-passed.json').write_text(json.dumps({'result':str(OUT/'result.json'), **result},indent=2))
    torch.save({k:v.cpu() for k,v in batch.items() if isinstance(v,torch.Tensor)}, OUT/'batch.pt')
    print(json.dumps(result),flush=True)
finally:
    factory.close()
